const codes = bank.map((c) => c.countryCode);
function missing(map) {
  return codes.filter((c) => !map[c]);
}

const gaps = {
  frCapitals: missing(frCapitals),
  esCapitals: missing(esCapitals),
  frCountries: missing(frCountries),
  esCountries: missing(esCountries),
};

for (const [key, value] of Object.entries(gaps)) {
  if (value.length) {
    throw new Error(`Missing ${key}: ${value.join(",")}`);
  }
}

const outDir = path.join(__dirname, "..", "lib", "quiz", "data");
fs.mkdirSync(outDir, { recursive: true });

const enCountries = Object.fromEntries(
  bank.map((c) => [c.countryCode, c.countryName])
);

fs.writeFileSync(
  path.join(outDir, "geoCapitals.json"),
  JSON.stringify({ en: enCaps, fr: frCapitals, es: esCapitals }, null, 2)
);
fs.writeFileSync(
  path.join(outDir, "geoCountries.json"),
  JSON.stringify({ en: enCountries, fr: frCountries, es: esCountries }, null, 2)
);

